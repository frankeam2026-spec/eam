CREATE TABLE eam_base_item (
    id BIGINT NOT NULL PRIMARY KEY,
    item_type VARCHAR(32) NOT NULL,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(100) NOT NULL,
    parent_id BIGINT NULL,
    decimal_precision TINYINT UNSIGNED NOT NULL DEFAULT 0,
    sort_no INT NOT NULL DEFAULT 0,
    status TINYINT NOT NULL DEFAULT 1 COMMENT '1 enabled, 0 disabled',
    deleted TINYINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_base_type_code (item_type, code),
    KEY idx_base_parent (item_type, parent_id, sort_no),
    KEY idx_base_status (item_type, status, deleted),
    CONSTRAINT fk_base_parent FOREIGN KEY (parent_id) REFERENCES eam_base_item(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='设备台账基础数据';

CREATE TABLE eam_equipment (
    id BIGINT NOT NULL PRIMARY KEY,
    equipment_code VARCHAR(32) NOT NULL,
    asset_no VARCHAR(80) NULL,
    tag_code VARCHAR(100) NULL,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(100) NOT NULL,
    model VARCHAR(120) NULL,
    serial_no VARCHAR(120) NULL,
    company VARCHAR(120) NOT NULL,
    department VARCHAR(120) NOT NULL,
    owner_name VARCHAR(80) NULL,
    location VARCHAR(200) NULL,
    brand VARCHAR(100) NULL,
    equipment_status VARCHAR(24) NOT NULL DEFAULT '在用',
    use_status VARCHAR(40) NULL,
    source VARCHAR(40) NULL,
    unit_name VARCHAR(40) NULL,
    supplier VARCHAR(160) NULL,
    purchase_date DATE NULL,
    acquired_at DATE NULL,
    acquired_amount DECIMAL(18,2) NULL,
    warranty_until DATE NULL,
    in_service_date DATE NULL,
    expected_retirement_date DATE NULL,
    equipment_level VARCHAR(30) NULL,
    function_location VARCHAR(200) NULL,
    special_equipment VARCHAR(8) NOT NULL DEFAULT '否',
    metrology_equipment VARCHAR(8) NOT NULL DEFAULT '否',
    depreciation_enabled VARCHAR(8) NOT NULL DEFAULT '否',
    technical_params VARCHAR(2000) NULL,
    certificate_status VARCHAR(40) NULL,
    certificate_until DATE NULL,
    english_name VARCHAR(160) NULL,
    image_name VARCHAR(255) NULL,
    documents_json JSON NULL,
    children_json JSON NULL,
    related_spares_json JSON NULL,
    description VARCHAR(1000) NULL,
    row_version INT NOT NULL DEFAULT 0,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_equipment_code (equipment_code),
    KEY idx_equipment_name (name),
    KEY idx_equipment_department_state (department, equipment_status, deleted),
    KEY idx_equipment_category_use (category, use_status, deleted),
    KEY idx_equipment_serial (serial_no),
    KEY idx_equipment_asset_no (asset_no),
    KEY idx_equipment_tag_code (tag_code),
    KEY idx_equipment_function_location (function_location),
    KEY idx_equipment_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='设备台账';

CREATE TABLE sys_number_counter (
    rule_code VARCHAR(40) NOT NULL,
    period_key VARCHAR(16) NOT NULL,
    next_value BIGINT NOT NULL,
    PRIMARY KEY (rule_code, period_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='业务编码序列';

